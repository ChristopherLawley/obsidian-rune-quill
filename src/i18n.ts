export type MessageKey = keyof typeof catalog.en;
type Messages = Record<MessageKey, string>;

export function messagesFor(language: string): Messages {
  const normalized = language.toLowerCase().replaceAll("_", "-");
  const parts = normalized.split("-");
  const base = parts[0];
  if (base === "zh") {
    return parts.some((part) => ["hant", "tw", "hk", "mo"].includes(part))
      ? catalog["zh-Hant"] : catalog["zh-Hans"];
  }
  if (base === "pt") return catalog["pt-BR"];
  const translations: Readonly<Record<string, Messages>> = catalog;
  return base && Object.hasOwn(translations, base) ? translations[base] ?? catalog.en : catalog.en;
}
